//! The generator output block (spec §23.3), its canonical decoding, and the
//! output root (spec §23.4).
//!
//! The block is a length-prefixed, little-endian, unaligned encoding. It is
//! **canonical**: one value has exactly one byte string, so
//! [`GeneratorOutput::output_root`] is injective — two runs that produce different
//! outputs cannot have the same root, which is what makes the determinism gate's
//! comparison meaningful.

use std::collections::BTreeSet;

/// The generator interface version this build implements (spec §23.5).
///
/// Re-exported from the crate root so the manifest's `generate.interface` can be
/// checked against the one value the host knows how to run.
pub const INTERFACE_VERSION: u32 = 1;

/// The WASM feature profile this build implements (spec §23.5).
pub const WASM_PROFILE: u32 = 1;

/// Domain label for the output root (spec §23.4). 24 ASCII bytes, no terminator.
pub const OUTPUT_LABEL: &[u8] = b"ctf/generator-output/v1";

/// Ceiling on the number of named outputs in one block. A challenge has tens of
/// artifacts; this is four orders of magnitude of headroom and keeps the decode
/// loop's allocation bounded before it starts.
pub const MAX_OUTPUTS: usize = 1024;

/// A generated byte stream's name cannot exceed a manifest name's length, because
/// it indexes the same name table (spec §7.2).
pub const MAX_OUTPUT_NAME_LEN: usize = 255;

/// The flag is short human-typable text; a generous cap keeps a hostile module
/// from making the host allocate arbitrarily.
pub const MAX_FLAG_LEN: usize = 4096;

/// A failure decoding an output block.
///
/// Every variant is static: a block is producer-controlled, not bundle bytes, but
/// the host still never echoes its content into a diagnostic (the same
/// no-oracle discipline as spec §13).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AbiError {
    /// The block ended before a declared length was satisfied.
    Truncated,
    /// The block had bytes after its last declared value.
    TrailingBytes,
    /// More than [`MAX_OUTPUTS`] named outputs.
    TooManyOutputs,
    /// An output name was empty, or longer than [`MAX_OUTPUT_NAME_LEN`].
    BadNameLength,
    /// An output name was not valid UTF-8.
    NameNotUtf8,
    /// Two outputs shared a name.
    DuplicateName,
    /// The blocks' output bytes together exceeded the caller's cap.
    OutputTooLarge,
    /// The flag was longer than [`MAX_FLAG_LEN`].
    FlagTooLong,
    /// The flag was not valid UTF-8.
    FlagNotUtf8,
}

impl core::fmt::Display for AbiError {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        let s = match self {
            Self::Truncated => "generator output block ended early",
            Self::TrailingBytes => "generator output block has trailing bytes",
            Self::TooManyOutputs => "generator output block declares too many outputs",
            Self::BadNameLength => "a generator output name is empty or too long",
            Self::NameNotUtf8 => "a generator output name is not valid UTF-8",
            Self::DuplicateName => "generator output names are not unique",
            Self::OutputTooLarge => "generator output exceeds the configured byte cap",
            Self::FlagTooLong => "the generator flag is too long",
            Self::FlagNotUtf8 => "the generator flag is not valid UTF-8",
        };
        f.write_str(s)
    }
}

impl core::error::Error for AbiError {}

/// One named generated byte stream.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Output {
    /// The output's name; an entry of the manifest's `names` table once packed.
    pub name: String,
    /// The bytes the generator produced for it.
    pub bytes: Vec<u8>,
}

/// The decoded result of one generator run: named outputs plus the flag.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GeneratorOutput {
    /// Named artifact byte streams, in the order the generator emitted them.
    pub outputs: Vec<Output>,
    /// The flag the generator computed for the run's seed.
    pub flag: String,
}

/// The artifact-only block a solver receives (spec §25.3).
///
/// It is the generator output block (§23.3) **without the flag**: the solver must
/// recover the flag from the artifacts, so handing it the generator's flag would
/// make the offline gate vacuous. Encoding it is exactly the output block's
/// `count × { name, data }` prefix.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ArtifactBlock {
    /// Named artifact byte streams, in the order the generator emitted them.
    pub outputs: Vec<Output>,
}

impl ArtifactBlock {
    /// Project a generator run's outputs into the solver's input.
    pub fn from_generator(output: &GeneratorOutput) -> Self {
        Self {
            outputs: output.outputs.clone(),
        }
    }

    /// The canonical encoding: `u32_le count` then `count × { name, data }`.
    pub fn encode(&self) -> Vec<u8> {
        let mut out = Vec::new();
        out.extend_from_slice(&(self.outputs.len() as u32).to_le_bytes());
        for o in &self.outputs {
            out.extend_from_slice(&(o.name.len() as u32).to_le_bytes());
            out.extend_from_slice(o.name.as_bytes());
            out.extend_from_slice(&(o.bytes.len() as u32).to_le_bytes());
            out.extend_from_slice(&o.bytes);
        }
        out
    }

    /// Decode an artifact block, rejecting anything not canonical for its value.
    pub fn decode(b: &[u8], max_output_bytes: usize) -> Result<Self, AbiError> {
        let mut at = 0usize;
        let count = u32_at(b, at).ok_or(AbiError::Truncated)? as usize;
        at += 4;
        if count > MAX_OUTPUTS {
            return Err(AbiError::TooManyOutputs);
        }
        let mut outputs = Vec::with_capacity(count);
        let mut names: BTreeSet<&str> = BTreeSet::new();
        let mut total = 0usize;
        for _ in 0..count {
            let name_len = u32_at(b, at).ok_or(AbiError::Truncated)? as usize;
            at += 4;
            if name_len == 0 || name_len > MAX_OUTPUT_NAME_LEN {
                return Err(AbiError::BadNameLength);
            }
            let name_end = at.checked_add(name_len).ok_or(AbiError::Truncated)?;
            let name_bytes = b.get(at..name_end).ok_or(AbiError::Truncated)?;
            let name = core::str::from_utf8(name_bytes).map_err(|_| AbiError::NameNotUtf8)?;
            if !names.insert(name) {
                return Err(AbiError::DuplicateName);
            }
            at = name_end;
            let data_len = u32_at(b, at).ok_or(AbiError::Truncated)? as usize;
            at += 4;
            total = total
                .checked_add(data_len)
                .ok_or(AbiError::OutputTooLarge)?;
            if total > max_output_bytes {
                return Err(AbiError::OutputTooLarge);
            }
            let data_end = at.checked_add(data_len).ok_or(AbiError::Truncated)?;
            let data = b.get(at..data_end).ok_or(AbiError::Truncated)?.to_vec();
            at = data_end;
            outputs.push(Output {
                name: name.to_owned(),
                bytes: data,
            });
        }
        if at != b.len() {
            return Err(AbiError::TrailingBytes);
        }
        Ok(Self { outputs })
    }

    /// The output with `name`, if the generator produced one.
    pub fn output(&self, name: &str) -> Option<&Output> {
        self.outputs.iter().find(|o| o.name == name)
    }
}

/// A little-endian `u32` at `at`, or `None` when the block ends before it.
fn u32_at(b: &[u8], at: usize) -> Option<u32> {
    Some(u32::from_le_bytes(b.get(at..at + 4)?.try_into().ok()?))
}

impl GeneratorOutput {
    /// The canonical encoding of §23.3.
    pub fn encode(&self) -> Vec<u8> {
        let mut out = Vec::new();
        out.extend_from_slice(&(self.outputs.len() as u32).to_le_bytes());
        for o in &self.outputs {
            out.extend_from_slice(&(o.name.len() as u32).to_le_bytes());
            out.extend_from_slice(o.name.as_bytes());
            out.extend_from_slice(&(o.bytes.len() as u32).to_le_bytes());
            out.extend_from_slice(&o.bytes);
        }
        out.extend_from_slice(&(self.flag.len() as u32).to_le_bytes());
        out.extend_from_slice(self.flag.as_bytes());
        out
    }

    /// Decode a block, rejecting anything that is not canonical for its value.
    ///
    /// `max_output_bytes` bounds the total artifact bytes, before the host copies
    /// them out of guest memory, so a module cannot make the host allocate an
    /// unbounded buffer regardless of its own memory cap.
    pub fn decode(b: &[u8], max_output_bytes: usize) -> Result<Self, AbiError> {
        let mut at = 0usize;
        let count = u32_at(b, at).ok_or(AbiError::Truncated)? as usize;
        at += 4;
        if count > MAX_OUTPUTS {
            return Err(AbiError::TooManyOutputs);
        }

        let mut outputs = Vec::with_capacity(count);
        let mut names: BTreeSet<&str> = BTreeSet::new();
        let mut total = 0usize;
        for _ in 0..count {
            let name_len = u32_at(b, at).ok_or(AbiError::Truncated)? as usize;
            at += 4;
            if name_len == 0 || name_len > MAX_OUTPUT_NAME_LEN {
                return Err(AbiError::BadNameLength);
            }
            let name_end = at.checked_add(name_len).ok_or(AbiError::Truncated)?;
            let name_bytes = b.get(at..name_end).ok_or(AbiError::Truncated)?;
            let name = core::str::from_utf8(name_bytes).map_err(|_| AbiError::NameNotUtf8)?;
            if !names.insert(name) {
                return Err(AbiError::DuplicateName);
            }
            at = name_end;

            let data_len = u32_at(b, at).ok_or(AbiError::Truncated)? as usize;
            at += 4;
            total = total
                .checked_add(data_len)
                .ok_or(AbiError::OutputTooLarge)?;
            if total > max_output_bytes {
                return Err(AbiError::OutputTooLarge);
            }
            let data_end = at.checked_add(data_len).ok_or(AbiError::Truncated)?;
            let data = b.get(at..data_end).ok_or(AbiError::Truncated)?.to_vec();
            at = data_end;

            outputs.push(Output {
                name: name.to_owned(),
                bytes: data,
            });
        }

        let flag_len = u32_at(b, at).ok_or(AbiError::Truncated)? as usize;
        at += 4;
        if flag_len > MAX_FLAG_LEN {
            return Err(AbiError::FlagTooLong);
        }
        let flag_end = at.checked_add(flag_len).ok_or(AbiError::Truncated)?;
        let flag_bytes = b.get(at..flag_end).ok_or(AbiError::Truncated)?;
        let flag = core::str::from_utf8(flag_bytes).map_err(|_| AbiError::FlagNotUtf8)?;
        at = flag_end;

        if at != b.len() {
            return Err(AbiError::TrailingBytes);
        }
        Ok(Self {
            outputs,
            flag: flag.to_owned(),
        })
    }

    /// `BLAKE3("ctf/generator-output/v1" ‖ block)` (spec §23.4).
    pub fn output_root(&self) -> [u8; 32] {
        let block = self.encode();
        let mut hasher = blake3::Hasher::new();
        hasher.update(OUTPUT_LABEL);
        hasher.update(&block);
        *hasher.finalize().as_bytes()
    }

    /// The output with `name`, if the generator produced one.
    pub fn output(&self, name: &str) -> Option<&Output> {
        self.outputs.iter().find(|o| o.name == name)
    }
}

/// Decode a solver output block: `u32_le flag_len ‖ flag bytes` (spec §25.4).
///
/// The solver's whole result is a flag, so the block is one length-prefixed string
/// and nothing else. Trailing bytes are rejected, matching the generator block's
/// canonicity rule.
pub fn decode_solver_flag(b: &[u8], max_flag_len: usize) -> Result<String, AbiError> {
    let mut at = 0usize;
    let flag_len = u32_at(b, at).ok_or(AbiError::Truncated)? as usize;
    at += 4;
    if flag_len > max_flag_len {
        return Err(AbiError::FlagTooLong);
    }
    let end = at.checked_add(flag_len).ok_or(AbiError::Truncated)?;
    let bytes = b.get(at..end).ok_or(AbiError::Truncated)?;
    let flag = core::str::from_utf8(bytes).map_err(|_| AbiError::FlagNotUtf8)?;
    at = end;
    if at != b.len() {
        return Err(AbiError::TrailingBytes);
    }
    Ok(flag.to_owned())
}

/// Reject an interface version this host does not implement (rule G6).
pub fn ensure_interface(interface: u32) -> Result<(), u32> {
    if interface == INTERFACE_VERSION {
        Ok(())
    } else {
        Err(interface)
    }
}

/// Reject a WASM profile this host does not implement (rule G7).
pub fn ensure_profile(profile: u32) -> Result<(), u32> {
    if profile == WASM_PROFILE {
        Ok(())
    } else {
        Err(profile)
    }
}
